# Create function that adds 2 numbers and returns the total
def add_numbers(x, y):
    return x + y

# Call the function with parameters
total1 = add_numbers(12, 24)
total2 = add_numbers(36, 47)

# Print totals - showing 2 ways to print the answer
print("The sum of 12 and 24 is:", total1)
print(f"The sum of 36 and 47 is: {total2}")