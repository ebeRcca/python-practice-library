# Challenge 1 - triangle

# What is the area of the triangle?
# Area of a triangle = 1/2 * base * height
# j = height
# k = base

print()

# User input for dimensions:
j = float(input("Enter the height j: "))
k = float(input("Enter the base k: "))

total_area = 1/2 * j * k

print("\nThe area of the triangle is", total_area, "\n")

# Assertion 1: j = 10, k = 7.5 > area = 37.5
# Assertion 2: j = 40, k = 30 > area = 600


